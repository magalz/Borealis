package io.github.magalz.borealis.buildlogic

import kotlinx.kover.gradle.plugin.dsl.KoverProjectExtension
import kotlinx.kover.gradle.plugin.dsl.KoverReportFiltersConfig
import org.gradle.api.Project
import org.gradle.kotlin.dsl.configure

/**
 * Kover coverage conventions (ADR 0046). Every Borealis module contributes the same custom variant,
 * built from its `debug` Android variant, so the root report can merge them all.
 */
internal object BorealisCoverage {
    const val PLUGIN_ID = "org.jetbrains.kotlinx.kover"

    /** Kover variant that merges the debug unit-test coverage of a module. */
    const val VARIANT = "borealis"

    /** The merged JaCoCo-format XML (the root `koverXmlReportBorealis` task), under `build/`. */
    const val XML_REPORT = "reports/kover/coverage.xml"

    /**
     * Classes the report leaves out, as Kover wildcards (`*` crosses dots, so `pkg.*` covers the
     * subpackages).
     *
     * No `com.limelight` class is left out: since Sprint 14 every one counts, the inherited Java
     * that is not converted yet included (ADR 0059), so the owner decides on its coverage from
     * measured numbers. Only the classes generated by Hilt/Dagger, Room and kotlinx.serialization,
     * and the other build outputs that would only add noise to the coverage numbers, are left out.
     */
    val EXCLUDED_CLASSES =
        listOf(
            "dagger.hilt.*",
            "hilt_aggregated_deps.*",
            "*.Hilt_*",
            "Hilt_*",
            "*_HiltModules*",
            "*_HiltComponents*",
            "*_Factory",
            "*_Factory$*",
            "*_Provide*Factory",
            "*_Provide*Factory$*",
            "*Module_*Factory",
            "*Module_*Factory$*",
            "*_MembersInjector",
            "*_GeneratedInjector",
            "*_Impl",
            "*_Impl$*",
            "*$\$serializer",
            "*.BuildConfig",
            "*.R",
            "*.R$*",
            "*ComposableSingletons*",
        )

    private const val PREVIEW_ANNOTATION = "androidx.compose.ui.tooling.preview.Preview"

    fun KoverReportFiltersConfig.borealisFilters() {
        excludes {
            classes(EXCLUDED_CLASSES)
            // @Preview composables only feed the IDE and the screenshot tests.
            annotatedBy(PREVIEW_ANNOTATION)
        }
    }

    /** Applies Kover to a Borealis module and publishes its `debug` variant as [VARIANT]. */
    fun Project.configureCoverage() {
        pluginManager.apply(PLUGIN_ID)
        extensions.configure<KoverProjectExtension> {
            currentProject { createVariant(VARIANT) { add("debug") } }
            reports { filters { borealisFilters() } }
        }
    }
}
