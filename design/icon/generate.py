"""Generate the Borealis launcher icon, the shortcut icon layers, the legacy launcher PNGs, the Google TV banner
and the mark of the design system.

One geometry source drives every output, so the art changes in one place. Run from the repository
root:

    python -I design/icon/generate.py [--font PATH] [--preview OUT.png]

It needs Pillow, and an OFL font for the banner wordmark (default: Noto Sans SC Bold).
"""
import argparse
import os
import textwrap

from PIL import Image, ImageDraw, ImageFilter, ImageFont

RES = os.path.join('apps', 'android', 'app', 'src', 'main', 'res')
DESIGNSYSTEM_RES = os.path.join('apps', 'android', 'borealis', 'designsystem', 'src', 'main', 'res')
LEGACY_SIZES = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}

BG_TOP, BG_BOTTOM = (0x1B, 0x0E, 0x3A), (0x3D, 0x1E, 0x7E)
RIDGE = (0x0E, 0x10, 0x13)
# The upper band is the teal of the accent (issue #50): the accent and the accent-strong of the teal set of
# design/accessibility/accents.json, which design/accessibility/test_icon_colours.py keeps equal.
TEAL_TOP, TEAL_BOTTOM = (0x4B, 0xEC, 0xD0, 0.95), (0x06, 0xAF, 0x97, 0.10)
VIOLET_TOP, VIOLET_BOTTOM = (0xC4, 0xB5, 0xFD, 0.85), (0x7C, 0x3A, 0xED, 0.10)
STAR = (0xF5, 0xF3, 0xFF, 0.9)

# 108 x 108 adaptive-icon geometry: launchers show the centred 72 x 72.
TEAL = [('M', 0, 66), ('C', 20, 44, 38, 62, 54, 36), ('C', 64, 20, 80, 30, 108, 14), ('L', 108, 30),
        ('C', 84, 42, 68, 32, 57, 50), ('C', 42, 72, 22, 54, 0, 80), ('Z',)]
VIOLET = [('M', 0, 76), ('C', 22, 56, 42, 74, 58, 52), ('C', 70, 38, 84, 46, 108, 36), ('L', 108, 48),
          ('C', 86, 56, 72, 50, 61, 62), ('C', 46, 80, 24, 64, 0, 88), ('Z',)]
RIDGE_PATH = [('M', 0, 84), ('L', 22, 74), ('L', 34, 80), ('L', 50, 66), ('L', 60, 75), ('L', 70, 69),
              ('L', 86, 80), ('L', 108, 74), ('L', 108, 108), ('L', 0, 108), ('Z',)]
STARS = [(38, 27, 0.9), (70, 24, 0.7), (29, 42, 0.6), (78, 52, 0.6), (48, 46, 0.5)]

# The layers of the one-colour mark, back to front, each as its path and its opacity. The themed icon, the
# mark of the design system and the monochrome raster of the preview draw these, so they cannot drift apart.
MONOCHROME_LAYERS = [(TEAL, 1), (VIOLET, 0.6), (RIDGE_PATH, 1)]

# A launcher shows the centred 72 x 72 of the 108 x 108 geometry: its offset and size, which the mark keeps.
SAFE_ZONE_OFFSET, SAFE_ZONE_SIZE = 18, 72

# Shortcut icon: a monitor (the host PC) in the same 108 x 108 geometry, inside the 72 x 72 safe zone. Its
# screen is a hole in the frame, so the launcher sky shows through; the aurora band sits inside it.
MONITOR = (28, 30, 52, 40, 5)  # x, y, width, height, corner radius of the outer frame
MONITOR_SCREEN = (33, 35, 42, 30, 2.5)
MONITOR_NECK = (49, 70, 10, 7, 0)
MONITOR_BASE = (38, 77, 32, 4, 2)
MONITOR_AURORA = [('M', 33, 62), ('C', 42, 50, 50, 58, 58, 47), ('C', 64, 40, 70, 42, 75, 38), ('L', 75, 46),
                  ('C', 70, 50, 64, 48, 60, 54), ('C', 52, 64, 42, 56, 33, 64), ('Z',)]


def alpha(c):
    return c[3] if len(c) > 3 else 1


def argb(c):
    return '#%02X%02X%02X%02X' % (int(round(alpha(c) * 255)), c[0], c[1], c[2])


def path_data(path):
    out = []
    for seg in path:
        k, v = seg[0], seg[1:]
        out.append(k + ' '.join(f'{v[i]:g},{v[i + 1]:g}' for i in range(0, len(v), 2)))
    return ' '.join(out)


def rect_data(x, y, w, h, r):
    if not r:
        return f'M{x:g},{y:g}h{w:g}v{h:g}h{-w:g}z'
    return (f'M{x + r:g},{y:g}h{w - 2 * r:g}a{r:g},{r:g} 0 0,1 {r:g},{r:g}v{h - 2 * r:g}'
            f'a{r:g},{r:g} 0 0,1 {-r:g},{r:g}h{-(w - 2 * r):g}a{r:g},{r:g} 0 0,1 {-r:g},{-r:g}'
            f'v{-(h - 2 * r):g}a{r:g},{r:g} 0 0,1 {r:g},{-r:g}z')


def circle_data(x, y, r):
    return f'M{x - r:g},{y:g}a{r:g},{r:g} 0 1,0 {2 * r:g},0a{r:g},{r:g} 0 1,0 {-2 * r:g},0'


# --- Vector drawables -----------------------------------------------------------------------------

HEADER = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    '<!-- Borealis launcher icon, {what} layer. Generated by design/icon/generate.py. -->\n'
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    xmlns:aapt="http://schemas.android.com/aapt"\n'
    '    android:width="108dp"\n'
    '    android:height="108dp"\n'
    '    android:viewportWidth="108"\n'
    '    android:viewportHeight="108">\n'
)


def gradient(top, bottom, y0, y1):
    return (
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient\n'
        '                android:type="linear"\n'
        '                android:startX="54"\n'
        f'                android:startY="{y0}"\n'
        '                android:endX="54"\n'
        f'                android:endY="{y1}">\n'
        f'                <item android:offset="0" android:color="{argb(top)}" />\n'
        f'                <item android:offset="1" android:color="{argb(bottom)}" />\n'
        '            </gradient>\n'
        '        </aapt:attr>'
    )


def solid(color, path):
    return f'    <path\n        android:fillColor="{color}"\n        android:pathData="{path}" />\n'


def even_odd(color, path):
    return (f'    <path\n        android:fillColor="{color}"\n        android:fillType="evenOdd"\n'
            f'        android:pathData="{path}" />\n')


def monochrome_paths():
    """The paths of the one-colour mark as vector-drawable elements: white, each at its opacity."""
    return ''.join(solid(argb((0xFF, 0xFF, 0xFF, a)), path_data(path)) for path, a in MONOCHROME_LAYERS)


def vectors(drawable_dir):
    background = HEADER.format(what='background') + (
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        f'{gradient(BG_TOP, BG_BOTTOM, 0, 108)}\n'
        '    </path>\n</vector>\n'
    )
    foreground = HEADER.format(what='foreground') + ''.join(
        solid(argb(STAR), circle_data(x, y, r)) for x, y, r in STARS
    ) + (
        f'    <path android:pathData="{path_data(VIOLET)}">\n'
        f'{gradient(VIOLET_TOP, VIOLET_BOTTOM, 36, 88)}\n    </path>\n'
        f'    <path android:pathData="{path_data(TEAL)}">\n'
        f'{gradient(TEAL_TOP, TEAL_BOTTOM, 14, 80)}\n    </path>\n'
        + solid(argb(RIDGE), path_data(RIDGE_PATH)) + '</vector>\n'
    )
    monochrome = HEADER.format(what='monochrome') + monochrome_paths() + '</vector>\n'
    shortcut_header = HEADER.replace('Borealis launcher icon, {what} layer', 'Borealis shortcut icon, {what} layer')
    frame = rect_data(*MONITOR) + rect_data(*MONITOR_SCREEN)
    stand = rect_data(*MONITOR_NECK) + rect_data(*MONITOR_BASE)
    shortcut_foreground = shortcut_header.format(what='foreground') + (
        even_odd(argb(STAR[:3]), frame)
        + solid(argb(STAR[:3]), stand)
        + f'    <path android:pathData="{path_data(MONITOR_AURORA)}">\n'
        f'{gradient(TEAL_TOP, TEAL_BOTTOM, 38, 66)}\n    </path>\n</vector>\n'
    )
    shortcut_monochrome = shortcut_header.format(what='monochrome') + (
        even_odd('#FFFFFFFF', frame)
        + solid('#FFFFFFFF', stand)
        + solid('#99FFFFFF', path_data(MONITOR_AURORA))
        + '</vector>\n'
    )
    for name, body in [('borealis_launcher_background', background),
                       ('borealis_launcher_foreground', foreground),
                       ('borealis_launcher_monochrome', monochrome),
                       ('borealis_shortcut_foreground', shortcut_foreground),
                       ('borealis_shortcut_monochrome', shortcut_monochrome)]:
        with open(os.path.join(drawable_dir, name + '.xml'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(body)


def mark(drawable_dir):
    """The monochrome launcher layer cropped to what a launcher shows, as a 24dp drawable for the design system.

    Its paths are the ones of the themed icon, so the two cannot drift apart. A screen tints it.
    """
    o, n = SAFE_ZONE_OFFSET, SAFE_ZONE_SIZE
    body = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Borealis mark: the monochrome launcher layer, cropped to what a launcher shows.'
        ' Generated by design/icon/generate.py. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        f'    android:viewportWidth="{n}"\n'
        f'    android:viewportHeight="{n}">\n'
        '    <group\n'
        f'        android:translateX="{-o}"\n'
        f'        android:translateY="{-o}">\n'
        f'        <clip-path android:pathData="{rect_data(o, o, n, n, 0)}" />\n'
        + textwrap.indent(monochrome_paths(), '    ')
        + '    </group>\n</vector>\n'
    )
    with open(os.path.join(drawable_dir, 'borealis_mark.xml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(body)


# --- Raster output (legacy PNGs and banner) -------------------------------------------------------

def flatten(path, sx, sy, ox, oy, steps=48):
    pts, cur = [], (0, 0)
    for seg in path:
        k = seg[0]
        if k in ('M', 'L'):
            cur = (seg[1], seg[2])
            pts.append(cur)
        elif k == 'C':
            p0, p1, p2, p3 = cur, (seg[1], seg[2]), (seg[3], seg[4]), (seg[5], seg[6])
            for i in range(1, steps + 1):
                t = i / steps
                u = 1 - t
                pts.append((u ** 3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t ** 3 * p3[0],
                            u ** 3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t ** 3 * p3[1]))
            cur = p3
    return [(x * sx + ox, y * sy + oy) for x, y in pts]


def vertical_gradient(w, h, top, bottom, y0, y1):
    column = Image.new('RGBA', (1, h))
    px = column.load()
    for y in range(h):
        t = min(1.0, max(0.0, (y - y0) / max(1.0, (y1 - y0))))
        rgb = tuple(int(round(top[i] + (bottom[i] - top[i]) * t)) for i in range(3))
        a = int(round(255 * (alpha(top) + (alpha(bottom) - alpha(top)) * t)))
        px[0, y] = rgb + (a,)
    return column.resize((w, h))


def fill(base, path, top, bottom, y0, y1, sx, sy, ox, oy):
    w, h = base.size
    mask = Image.new('L', (w, h), 0)
    ImageDraw.Draw(mask).polygon(flatten(path, sx, sy, ox, oy), fill=255)
    layer = vertical_gradient(w, h, top, bottom, y0 * sy + oy, y1 * sy + oy)
    layer.putalpha(Image.composite(layer.getchannel('A'), Image.new('L', (w, h), 0), mask))
    base.alpha_composite(layer)


def icon(size, monochrome=False):
    s = 4
    w = 108 * s
    if monochrome:
        img = Image.new('RGBA', (w, w), (0x2B, 0x29, 0x30, 255))
        light = (0xE6, 0xE0, 0xE9)
        for path, a in MONOCHROME_LAYERS:
            fill(img, path, light + (a,), light + (a,), 0, 108, s, s, 0, 0)
    else:
        img = vertical_gradient(w, w, BG_TOP, BG_BOTTOM, 0, w)
        draw = ImageDraw.Draw(img)
        for x, y, r in STARS:
            draw.ellipse([(x - r) * s, (y - r) * s, (x + r) * s, (y + r) * s], fill=(0xF5, 0xF3, 0xFF, 230))
        fill(img, VIOLET, VIOLET_TOP, VIOLET_BOTTOM, 36, 88, s, s, 0, 0)
        fill(img, TEAL, TEAL_TOP, TEAL_BOTTOM, 14, 80, s, s, 0, 0)
        fill(img, RIDGE_PATH, RIDGE, RIDGE, 0, 108, s, s, 0, 0)
    return img.crop((18 * s, 18 * s, 90 * s, 90 * s)).resize((size, size), Image.Resampling.LANCZOS)


def masked(img, shape):
    n = img.size[0]
    big = n * 4
    mask = Image.new('L', (big, big), 0)
    draw = ImageDraw.Draw(mask)
    if shape == 'circle':
        draw.ellipse([0, 0, big - 1, big - 1], fill=255)
    elif shape == 'rounded':
        draw.rounded_rectangle([0, 0, big - 1, big - 1], radius=big * 0.2, fill=255)
    else:
        draw.rounded_rectangle([0, 0, big - 1, big - 1], radius=big * 0.42, fill=255)
    out = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    out.paste(img, (0, 0), mask.resize((n, n), Image.Resampling.LANCZOS))
    return out


def banner(out, font_path):
    s = 4
    w, h = 640 * s, 360 * s
    img = vertical_gradient(w, h, BG_TOP, BG_BOTTOM, 0, h)
    sx, sy, ox, oy = w / 108, h / 108 * 0.9, 0, h * 0.02
    draw = ImageDraw.Draw(img)
    extra = [(16, 20, 0.6), (94, 14, 0.5), (60, 10, 0.5), (8, 50, 0.5), (100, 60, 0.4)]
    for x, y, r in STARS + extra:
        cx, cy, rr = x * sx + ox, y * sy * 0.8 + oy, r * 6 * s / 4
        draw.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=(STAR[0], STAR[1], STAR[2], int(STAR[3] * 255)))
    fill(img, VIOLET, VIOLET_TOP, VIOLET_BOTTOM, 36, 88, sx, sy, ox, oy)
    fill(img, TEAL, TEAL_TOP, TEAL_BOTTOM, 14, 80, sx, sy, ox, oy)
    fill(img, RIDGE_PATH, RIDGE, RIDGE, 0, 108, sx, sy, ox, oy)
    # The stretched ridge stops short of the bottom edge: extend it.
    draw.rectangle([0, 108 * sy + oy - 1, w, h], fill=RIDGE + (255,))
    font = ImageFont.truetype(font_path, 74 * s)
    text = 'Borealis'
    box = draw.textbbox((0, 0), text, font=font)
    tx = (w - (box[2] - box[0])) / 2 - box[0]
    ty = h * 0.80 - (box[3] - box[1]) / 2 - box[1]
    shadow = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(shadow).text((tx, ty + 3 * s), text, font=font, fill=(0, 0, 0, 160))
    img.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(6 * s)))
    ImageDraw.Draw(img).text((tx, ty), text, font=font, fill=(0xF5, 0xF3, 0xFF, 255))
    img.resize((640, 360), Image.Resampling.LANCZOS).convert('RGB').save(out, optimize=True)


def preview(out, banner_path):
    sheet = Image.new('RGBA', (1000, 760), (0x12, 0x12, 0x12, 255))
    draw = ImageDraw.Draw(sheet)
    draw.text((24, 16), 'Launcher icon: circle, squircle, rounded square, themed, 72 px and 48 px',
              fill=(220, 220, 220))
    x = 24
    for shape in ['circle', 'squircle', 'rounded']:
        sheet.alpha_composite(masked(icon(192), shape), (x, 44))
        x += 212
    sheet.alpha_composite(masked(icon(192, monochrome=True), 'circle'), (x, 44))
    x += 212
    sheet.alpha_composite(masked(icon(72), 'circle'), (x, 44))
    sheet.alpha_composite(masked(icon(48), 'circle'), (x + 12, 140))
    light = Image.new('RGBA', (220, 130), (0xF2, 0xF2, 0xF2, 255))
    light.alpha_composite(masked(icon(96), 'circle'), (12, 17))
    light.alpha_composite(masked(icon(96), 'squircle'), (112, 17))
    sheet.alpha_composite(light, (24, 256))
    draw.text((24, 400), 'Google TV banner (320 x 180 dp, xhdpi 640 x 360)', fill=(220, 220, 220))
    tv = Image.open(banner_path).convert('RGBA')
    sheet.alpha_composite(tv.resize((320, 180), Image.Resampling.LANCZOS), (24, 428))
    sheet.alpha_composite(tv.resize((560, 315), Image.Resampling.LANCZOS), (370, 428))
    sheet.convert('RGB').save(out)


def main():
    parser = argparse.ArgumentParser(description='Generate the Borealis launcher icon and TV banner.')
    parser.add_argument('--font', default=os.path.join('C:' + os.sep, 'Windows', 'Fonts', 'NotoSansSC-Bold.ttf'))
    parser.add_argument('--preview', help='also write a preview sheet to this PNG')
    args = parser.parse_args()
    vectors(os.path.join(RES, 'drawable'))
    mark_dir = os.path.join(DESIGNSYSTEM_RES, 'drawable')
    os.makedirs(mark_dir, exist_ok=True)
    mark(mark_dir)
    banner_path = os.path.join(RES, 'drawable-xhdpi', 'atv_banner.png')
    banner(banner_path, args.font)
    for density, size in LEGACY_SIZES.items():
        masked(icon(size), 'circle').save(os.path.join(RES, 'mipmap-' + density, 'ic_launcher.png'), optimize=True)
    if args.preview:
        preview(args.preview, banner_path)


if __name__ == '__main__':
    main()
